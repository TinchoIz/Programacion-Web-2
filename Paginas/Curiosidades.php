            <h2 class="h2-curiosidades">Curiosidades destacadas:</h2>

            <ol class="lista-curiosidades">
                <li class="item-curiosidad">Yoda iba a llamarse "Minch": Originalmente, el maestro Jedi se llamaría
                    Minch Yoda, hasta que decidieron acortarlo. Además, su rostro fue inspirado en el escultor de la
                    máscara y en Albert Einstein.</li>
                <li class="item-curiosidad">Harrison Ford no era la primera opción: Lucas no quería actores de su
                    película anterior, American Graffiti, pero la química de Ford con Mark Hamill y Carrie Fisher lo
                    convenció.</li>
                <li class="item-curiosidad">Chewbacca basado en una mascota: George Lucas se inspiró en su perro, un
                    Malamute de Alaska llamado Indiana, para crear al fiel compañero Wookiee.</li>
                <li class="item-curiosidad">Sables de luz y sonido: El característico sonido de los sables de luz se
                    creó combinando el zumbido de un proyector de cine viejo y la interferencia de un televisor.</li>
                <li class="item-curiosidad">Cameos de Lucas: George Lucas aparece como el Barón Papanoida en el Episodio
                    III (La Venganza de los Sith).</li>
                <li class="item-curiosidad">E.T. en el Senado: En el Episodio I (La Amenaza Fantasma), se puede ver a
                    miembros de la raza de E.T. en el Senado Galáctico, un homenaje de Lucas a Steven Spielberg.</li>
                <li class="item-curiosidad">Uniformes nazis: Para crear la estética del Imperio, se inspiraron en
                    uniformes militares de la Alemania nazi para resaltar la sensación de autoridad autoritaria.</li>
                <li class="item-curiosidad">La apuesta de Spielberg: Steven Spielberg apostó con George Lucas que Star
                    Wars no tendría éxito. Lucas le prometió el 2.5% de las ganancias a Spielberg, quien ha ganado
                    millones gracias a esa apuesta.</li>
                <li class="item-curiosidad">Actualidad de Locaciones: Muchas de las casas construidas en el desierto de
                    Túnez para caracterizar a Tatooine, el planeta de Luke, siguen en pie y son utilizadas por los
                    pobladores de la zona.</li>
                <li class="item-curiosidad">Greedo, el hombre verde al que Han Solo dispara en un bar en Episodio IV,
                    habla en quechua.</li>
